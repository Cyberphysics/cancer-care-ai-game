import * as path from 'node:path';
import * as cdk from 'aws-cdk-lib';
import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';
import * as origins from 'aws-cdk-lib/aws-cloudfront-origins';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as s3deploy from 'aws-cdk-lib/aws-s3-deployment';
import { Construct } from 'constructs';
import { AppConfig } from './config';
import { resourceName } from './naming';

export interface FrontendStackProps extends cdk.StackProps {
  readonly config: AppConfig;
}

/**
 * SPA rewrite for client-side routing.
 *
 * A CloudFront Function is used rather than mapping 403/404 → /index.html.
 * The error-response approach also swallows a *missing asset*: requesting a
 * deleted `/assets/index-abc.js` would return index.html with a 200, producing
 * "Uncaught SyntaxError: Unexpected token '<'" in the browser instead of a clean
 * 404. Rewriting only extension-less paths keeps asset 404s honest.
 *
 * Associated with the default behavior only — never with `/assets/*`.
 */
const SPA_REWRITE_CODE = `
function handler(event) {
  var request = event.request;
  var uri = request.uri;
  if (uri.indexOf('.') !== -1) { return request; }
  request.uri = '/index.html';
  return request;
}
`;

/**
 * Static layer: the React build in a private bucket behind CloudFront.
 *
 * Isolated in its own stack because CloudFront create/update takes 5–15 minutes.
 * Backend iteration must never wait on that.
 */
export class FrontendStack extends cdk.Stack {
  public readonly distribution: cloudfront.Distribution;
  public readonly webBucket: s3.Bucket;
  public readonly gameAssetsBucket: s3.Bucket;

  constructor(scope: Construct, id: string, props: FrontendStackProps) {
    super(scope, id, props);

    const { config } = props;

    // Physical names are generated by CloudFormation on purpose. A hardcoded
    // bucket name survives the bucket's deletion for a while, so a
    // destroy-then-redeploy cycle fails with BucketAlreadyExists.
    this.webBucket = new s3.Bucket(this, 'WebBucket', {
      encryption: s3.BucketEncryption.S3_MANAGED,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      versioned: false,
      removalPolicy: config.removalPolicy,
      autoDeleteObjects: config.autoDeleteObjects,
    });

    /**
     * Game resources, images and stage configuration (GDD §11). Ships empty in
     * Phase 0; Phase 2 populates it with synthetic case data.
     */
    this.gameAssetsBucket = new s3.Bucket(this, 'GameAssetsBucket', {
      encryption: s3.BucketEncryption.S3_MANAGED,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      versioned: false,
      removalPolicy: config.removalPolicy,
      autoDeleteObjects: config.autoDeleteObjects,
      lifecycleRules: [
        { abortIncompleteMultipartUploadAfter: cdk.Duration.days(7) },
        { prefix: 'tmp/', expiration: cdk.Duration.days(7) },
      ],
    });

    const spaRewrite = new cloudfront.Function(this, 'SpaRewriteFunction', {
      functionName: resourceName('spa-rewrite'),
      comment: 'Rewrite extension-less paths to /index.html for client-side routing',
      code: cloudfront.FunctionCode.fromInline(SPA_REWRITE_CODE),
      runtime: cloudfront.FunctionRuntime.JS_2_0,
    });

    // Built once and shared by both behaviors. Calling
    // `withOriginAccessControl()` per behavior would create a second,
    // redundant OAC for the same bucket.
    const webOrigin = origins.S3BucketOrigin.withOriginAccessControl(this.webBucket);

    // Behaviour note: because OAC + BlockPublicAccess grant no `s3:ListBucket`,
    // S3 answers a request for a missing key with 403 AccessDenied rather than
    // 404, and CloudFront passes that through. This is the expected outcome —
    // the important property is that a missing asset is never masked as
    // index.html with a 200 (see SPA_REWRITE_CODE above). Mapping 403 → 404
    // would require shipping a separate error page via `ResponsePagePath`,
    // which is not worth the extra moving parts at Phase 0.

    this.distribution = new cloudfront.Distribution(this, 'WebDistribution', {
      comment: `${config.appName} web client`,
      defaultRootObject: 'index.html',
      // No custom domain or ACM certificate in Phase 0 — the default
      // *.cloudfront.net domain is sufficient and avoids DNS validation wait.
      defaultBehavior: {
        origin: webOrigin,
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        // index.html must never be served stale after a deploy.
        cachePolicy: cloudfront.CachePolicy.CACHING_DISABLED,
        functionAssociations: [
          { function: spaRewrite, eventType: cloudfront.FunctionEventType.VIEWER_REQUEST },
        ],
      },
      additionalBehaviors: {
        // Vite content-hashes these filenames, so they are safe to cache hard.
        '/assets/*': {
          origin: webOrigin,
          viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
          cachePolicy: cloudfront.CachePolicy.CACHING_OPTIMIZED,
        },
      },
      priceClass: cloudfront.PriceClass.PRICE_CLASS_100,
      enableLogging: false,
    });

    // `Source.asset` validates the directory at synth time, so `frontend/dist`
    // must exist before `cdk synth` — i.e. build the web app first.
    new s3deploy.BucketDeployment(this, 'DeployWeb', {
      sources: [s3deploy.Source.asset(path.join(__dirname, '..', '..', '..', 'frontend', 'dist'))],
      destinationBucket: this.webBucket,
      distribution: this.distribution,
      distributionPaths: ['/*'],
      prune: true,
    });

    new cdk.CfnOutput(this, 'DistributionDomainName', {
      value: this.distribution.distributionDomainName,
      description: 'CloudFront domain serving the web client',
    });

    new cdk.CfnOutput(this, 'WebBucketName', {
      value: this.webBucket.bucketName,
      description: 'S3 bucket holding the built web client',
    });

    new cdk.CfnOutput(this, 'GameAssetsBucketName', {
      value: this.gameAssetsBucket.bucketName,
      description: 'S3 bucket for game assets and configuration',
    });
  }
}
